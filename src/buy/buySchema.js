let mongoose = require('mongoose'),
Schema = mongoose.Schema;
const BuySchema = new Schema({
    user: { type: Schema.Types.ObjectId, ref:'user' },
    product: { type: Schema.Types.ObjectId, ref:'product' },
    buyer: { type: Schema.Types.ObjectId, ref:'user' },
    buyerName: {type: String}, 
    number: { type: String },
    quantity: { type: Number, required: [true, 'Cantidad es obligatorio.'] },
    total: { type: Number, required: [true, 'Total es obligatorio.'] },
    address: { type: String },
    city: { type: String },
    cityBuyer: { type: String },
    customDelivery: { type: Boolean, default : false },
    department: { type: String },
    departmentBuyer: { type: String },
    name:{ type: String, required: [true, 'Nombre es obligatorio.']  },
    identification:{ type: String, required: [true, 'Identificación es obligatorio.']  },
    phone:{ type: String, required: [true, 'Teléfono es obligatorio.']  },
    qualifyBuyer: { type: String, default:'none'},
    qualifySeller: { type: String, default:'none'},
    buyerComment: { type: String},
    sellerComment: { type: String},
    messages: [{ type: Schema.Types.ObjectId, ref:'messageBuy' }],
    gain:{ type: Number},
    report:{ type: Number, default: 0},
    reportComment:{ type: String},
    commission:{ type: Number},
    payment: [],    
    highlight: { type: String },
    percent: { type: Number},
    status: { type: Number, default : 1 },
    createdSeller: { type: Date },
    createdBuyer: { type: Date },    
    month:{ type:Number },
    year: { type:Number },
    createdAt: { type: Date, default: Date.now }
});
module.exports = mongoose.model('buy',BuySchema);